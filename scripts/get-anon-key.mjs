// Generates Supabase API keys from the project JWT secret and writes .env.local.
// Usage: npm run db:anon-key
// Fallback: copy the anon key manually from Supabase Dashboard -> Settings -> API.
import { writeFileSync, readFileSync } from 'node:fs';
import { createHmac } from 'node:crypto';
import { connect } from './_db.mjs';

const PROJECT_REF = 'hioosnvcuxoslehjkgxl';
const SUPABASE_URL = `https://${PROJECT_REF}.supabase.co`;

function toText(value) {
  if (value == null) return null;
  if (Buffer.isBuffer(value)) return value.toString('utf8');
  if (typeof value === 'object' && value.type === 'Buffer' && Array.isArray(value.data)) {
    return Buffer.from(value.data).toString('utf8');
  }
  return String(value);
}

function sign(payload, secret) {
  const b64 = (obj) => Buffer.from(JSON.stringify(obj)).toString('base64url');
  const header = b64({ alg: 'HS256', typ: 'JWT' });
  const body = b64(payload);
  const signature = createHmac('sha256', secret).update(`${header}.${body}`).digest('base64url');
  return `${header}.${body}.${signature}`;
}

function makeKey(role, secret) {
  const now = Math.floor(Date.now() / 1000);
  return sign(
    { iss: 'supabase', ref: PROJECT_REF, role, iat: now, exp: now + 60 * 60 * 24 * 365 * 10 },
    secret
  );
}

const client = await connect();
console.log('Connected to Postgres.');

let secret = null;

try {
  // Discover candidate tables that might hold the JWT signing secret.
  const { rows: tables } = await client.query(
    `select table_schema, table_name
       from information_schema.tables
      where table_name ilike '%secret%' or table_name ilike '%jwt%'`
  );
  console.log('Secret-like tables:', tables.map((t) => `${t.table_schema}.${t.table_name}`).join(', ') || '(none)');

  const candidates = [];
  if (tables.some((t) => t.table_schema === 'auth' && t.table_name === 'secrets')) {
    candidates.push('select * from auth.secrets limit 5');
  }
  if (tables.some((t) => t.table_schema === 'vault' && t.table_name === 'decrypted_secrets')) {
    candidates.push('select * from vault.decrypted_secrets limit 20');
  }
  if (tables.some((t) => t.table_schema === 'auth' && t.table_name === 'jwt_secrets')) {
    candidates.push('select * from auth.jwt_secrets limit 5');
  }

  for (const query of candidates) {
    if (secret) break;
    try {
      const { rows } = await client.query(query);
      for (const row of rows) {
        for (const value of Object.values(row)) {
          const text = toText(value);
          if (text && text.length >= 32 && !/\s/.test(text)) {
            secret = text;
            console.log(`Secret found via "${query}"`);
            break;
          }
        }
        if (secret) break;
      }
    } catch (error) {
      console.log(`${query} -> ${error.message}`);
    }
  }
} finally {
  await client.end();
}

if (!secret) {
  console.error(
    '\nCould not extract the JWT secret from the database.\n' +
      'Fallback: Supabase Dashboard -> Settings -> API -> copy the anon key,\n' +
      'then paste it into .env.local as NEXT_PUBLIC_SUPABASE_ANON_KEY.'
  );
  process.exit(1);
}

const anonKey = makeKey('anon', secret);
const serviceRoleKey = makeKey('service_role', secret);

let existingDatabaseUrl = '';
try {
  existingDatabaseUrl = readFileSync(new URL('../.env.local', import.meta.url), 'utf8')
    .split('\n')
    .find((line) => line.startsWith('DATABASE_URL=')) ?? '';
} catch {
  /* no .env.local yet */
}

const envContent = `# Generated by scripts/get-anon-key.mjs — do not commit (gitignored)
NEXT_PUBLIC_SUPABASE_URL=${SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_ALLOWED_ORIGINS=http://localhost:3000
${existingDatabaseUrl}
`;

writeFileSync(new URL('../.env.local', import.meta.url), envContent);
console.log('\n.env.local written.');
console.log('NEXT_PUBLIC_SUPABASE_URL      =', SUPABASE_URL);
console.log('NEXT_PUBLIC_SUPABASE_ANON_KEY =', anonKey);
console.log('SERVICE ROLE KEY (server only, not in .env.local):', serviceRoleKey);
